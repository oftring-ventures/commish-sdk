import manifest from "../package.json" with { type: "json" };
import { inspectRepository } from "./setup-plan.mjs";

// @commish/next peer ranges; scripts/init-command.test.mjs keeps them equal to its manifest.
export const nextPeers = { next: ">=16.3.8 <17", react: ">=19.2.8 <20" };
const managers = {
  pnpm: { add: "pnpm add --save-exact", exec: "pnpm exec" },
  npm: { add: "npm install --save-exact", exec: "npx" },
  yarn: { add: "yarn add --exact", exec: "yarn" },
  bun: { add: "bun add --exact", exec: "bunx" },
};
const docs = "https://commish.sh/docs.md";
const schema = "https://app.commish.sh/api/cli/setup/capabilities";
const sdkGuide = `https://github.com/oftring-ventures/commish-sdk/blob/v${manifest.version}/packages/sdk/README.md`;

// The agent playbook ships with the CLI that runs it. Like planning, it reads only
// package.json and the presence of lockfiles and app directories: no network, no
// writes, no repository scripts.
export function initGuide(root) {
  const repository = inspectRepository(root);
  const manager = managers[repository.packageManager] ?? managers.npm;
  const next = repository.adapter === "next_peer_check_required";
  const cli = `${manager.exec} commish`;
  const packages = [`@commish/sdk@${manifest.version}`];
  if (next) packages.push(`@commish/next@${manifest.version}`);
  const commands = {
    install: `${manager.add} ${packages.join(" ")}`,
    plan: `${cli} setup --plan --json`,
    provision: `${cli} setup --config commish.setup.json --mode test --no-open --non-interactive --json`,
    ...(next ? { wire: `${manager.exec} commish-next --json` } : {}),
    verify: `${cli} verify --json`,
  };
  return {
    status: "guide",
    guideVersion: 1,
    sdkVersion: manifest.version,
    mutations: false,
    networkRequests: false,
    repository,
    commands,
    markdown: render(repository, commands, next, cli),
    integrationVerified: false,
  };
}

function render(repository, commands, next, cli) {
  const { sdkDeclared, nextDeclared } = repository.packages;
  const framework = next
    ? `Next.js App Router in \`${repository.appDirectories[0]}/\`. Use @commish/next only when the installed next satisfies ${nextPeers.next} and react satisfies ${nextPeers.react}; otherwise install only @commish/sdk and wire it yourself.`
    : repository.framework === "next"
      ? "Next.js without a single app directory. Use @commish/sdk and wire it yourself."
      : "Not detected. Use @commish/sdk and wire it yourself.";
  const wire = next
    ? `Run \`${commands.wire}\`, then the same command with \`--write\`, and follow its next steps for the layout and Checkout handler.`
    : `Follow the SDK guide (${sdkGuide}): capture the referral with \`captureReferral\` from \`@commish/sdk/browser\` through a same-origin capture route, and add the captured attribution to Stripe Checkout metadata as \`commish_attribution\`.`;
  return `# Set up Commish in this repository

Generated by the Commish CLI ${manifest.version} from a local scan: no network requests, no files written. Follow the steps in order. If you cannot read a linked source, say so and ask for its contents.

## This repository
${repository.warnings.includes("package_manifest_missing") ? "\n- No package.json here. Run this command again from the application's root directory.\n" : "\n"}- Package manager: ${repository.packageManager === "unknown" ? "not detected. Use the repository's own; the commands below use npm." : repository.packageManager}
- Framework: ${framework}
- Installed: ${sdkDeclared ? (nextDeclared ? "@commish/sdk and @commish/next" : "@commish/sdk") : "no Commish packages"}${repository.warnings.length ? `\n- Warnings: ${repository.warnings.join(", ")}` : ""}

## Rules

- Ask the person for every business choice together: eligible Stripe products, commission, recurrence, per-sale cap, disclosure text, webhook, Stripe connection and participant consent. Never invent them or the mode.
- Provision only through this CLI. The person completes authentication and consent in the browser. Stop and report blockers; do not automate the dashboard instead.
- Keep credentials in the private files setup writes, and out of chat, logs, Git and browser code. Resolve any policy against local credential storage before provisioning.
- Start in TEST. LIVE needs the person's explicit choice and current eligibility. Program activation and participant acceptance stay explicit.

## Steps

1. Install exact versions: \`${commands.install}\`. If the repository enforces a minimum package age, use the newest release that satisfies it.
2. Plan without an account: \`${commands.plan}\`. It reports missing inputs by field. Collect the business choices together, then write non-secret \`commish.setup.json\` (schema: ${schema}). An empty eligible-product list means all Stripe products.
3. Authorize and provision: \`${commands.provision}\`. Show the person the \`approvalUrl\` and \`pairingCode\` from the \`authorization_required\` JSON line on stderr; new users sign up there. The CLI waits, then provisions. After an interruption, rerun the same command.
4. Publish the generated proof file at the HTTPS URL the CLI prints.
5. Wire the application. ${wire} Let Commish record purchases and refunds from Stripe events; do not also send them as direct conversion or refund writes.
6. Check the configuration: supply \`.commish/setup/test/credentials.env\` to the environment, then run \`${commands.verify}\`. Configuration verified is not integration verified.
7. Prove an attributed TEST conversion. The workspace owner adds the creator role to their own account at https://app.commish.sh/account/roles?role=creator if needed, creates a test partnership for their own account from the program's Integration tab, and buys through its TEST referral link. Do not invite a separate creator email. Read the recorded conversion and commission.

## Report

Report package installation, configuration verification and the attributed TEST conversion as separate milestones, with evidence and any remaining actions.

## References

- Guide: ${docs}
- SDK guide for this version: ${sdkGuide}
- Workflow contract: \`${cli} agent --json\`; every command: \`${cli} --help\`
`;
}

export function runInitCommand(args, { root = process.cwd(), out = console.log } = {}) {
  if (args.length === 1 && ["--help", "-h"].includes(args[0])) {
    out(
      "Usage: commish init [--json]\nPrints a setup playbook for coding agents from a local scan of this repository. Reads package.json and checks which lockfiles and app directories exist; makes no network requests and writes no files.",
    );
    return 0;
  }
  if (args.some((arg) => arg !== "--json") || new Set(args).size !== args.length) {
    console.error(
      args.includes("--json")
        ? JSON.stringify({ status: "error", code: "invalid_arguments" })
        : "Usage: commish init [--json]",
    );
    return 1;
  }
  const guide = initGuide(root);
  out(args.includes("--json") ? JSON.stringify(guide) : guide.markdown);
  return 0;
}
